# ══════════════════════════════════════════════════════════════════
# 상품 4계층 — 단일 단가를 버리고 층위별로 분리한다
# ══════════════════════════════════════════════════════════════════

# ── T0 · 출강형 특강 (E-0635 · 근거 E-1040 실측 밴드 그대로) ──
# 강사가 기업으로 간다. 공간 원가 0 → 공사 기간 중에도 판매 가능한 유일한 상품.
T0_FEE = [500_000, 1_200_000, 2_000_000]        # E-1040 실측 50~200만 그대로
T0_CLIENT = [8, 15, 25]                          # 1년차 신규 고객사
T0_FREQ = [2, 3, 4]                              # 고객사당 연 회차
# 고객사 수 근거: 마보가 100여 개 기업·기관에 도입(E-1040). 이것이 유일한 실측 앵커다.
# 마보는 앱 기반 전국구 선도 사업자가 수년간 영업해 쌓은 누적치이므로,
# 신설 시설의 1년차를 그 8~25% 구간으로 잡았다. 이 비율 자체는 여전히 C등급 가정이다.

# ── T1 · 내방 매스형 연수 (E-0658 · 1인 단가 E-1042) ──
# 70~100명 규격 커리큘럼. 대공간을 쓰므로 대관과 날짜가 부딪친다.
T1_PP = [50_000, 70_000, 100_000]                # 1인 단가 — E-1042 차명상 3~7만 + 정통성 프리미엄
T1_CAP = [40, 60, 80]                            # 회당 정원
T1_N = [6, 18, 24]                               # 연 건수 (낙관은 §대공간 검산으로 35→24 캘리브레이션)

# ── T2 · 프리미엄 리트리트 (E-0636 · E-0659) ──
# 스님이 직접 진행. 소수정예라 명상웰니스 500㎡에서 소화 → 대공간 경쟁 없음.
# 대신 진행 주체가 스님이라 공급 상한이 사람 수로 걸린다.
T2_PP = [150_000, 250_000, 400_000]
T2_CAP = [12, 16, 20]
T2_N = [4, 12, 18]

# ── T3 · 연간 계약 (E-0637 · E-0660) ──
# 회차 판매를 반복 매출로 바꾸는 층. ※ RL-10 법인 멤버십과 지갑이 겹친다 (아래 경고 참조)
T3_FEE = [15_000_000, 25_000_000, 40_000_000]
T3_N = [1, 4, 6]
T3_SESSION = [4, 4, 6]                           # 계약사당 연 내방 세션 수(대공간 사용분)

def rev_t0(i): return T0_FEE[i] * T0_CLIENT[i] * T0_FREQ[i]
def rev_t1(i): return T1_PP[i] * T1_CAP[i] * T1_N[i]
def rev_t2(i): return T2_PP[i] * T2_CAP[i] * T2_N[i]
def rev_t3(i): return T3_FEE[i] * T3_N[i]
def rev_all(i): return rev_t0(i) + rev_t1(i) + rev_t2(i) + rev_t3(i)

# ══════════════════════════════════════════════════════════════════
# 원가 — 계층마다 다르다
# ══════════════════════════════════════════════════════════════════
C_T0 = [0.30, 0.28, 0.25]     # 강사료·이동 (공간·설비 원가 0)
C_T1 = [0.40, 0.36, 0.32]     # 공간 기회비용 + 다과 + 진행 인력
C_T2 = [0.45, 0.42, 0.38]     # 스님 진행 + 맞춤 설계 + 소수정예 밀도
C_T3 = [0.38, 0.34, 0.30]

WAGE = 3.5e7
STAFF_OWN = [2, 3, 4]          # (a) B2B 전담 영업조직
STAFF_SHARE = [1.0, 1.5, 2.0]  # (b) 대관·멤버십과 영업 겸임
MKT = [0.08, 0.06, 0.05]

def gross(i):
    return (rev_t0(i)*(1-C_T0[i]) + rev_t1(i)*(1-C_T1[i])
            + rev_t2(i)*(1-C_T2[i]) + rev_t3(i)*(1-C_T3[i]))

def op(i, staff):
    return gross(i) - staff[i]*WAGE - rev_all(i)*MKT[i]

# ══════════════════════════════════════════════════════════════════
# 대공간 검산 — 이 라인의 진짜 제약
# ══════════════════════════════════════════════════════════════════
HALL_CAP = [152, 152, 180]     # 대공간 연 판매가능일 (SETEC 실측 41.7%=152일 · 낙관은 상향여지 반영)
RENT_DAYS_RAW = [60, 100, 140]  # RL-08 대관 가동일 — 마스터 v0.2 가정 그대로
RENT_DAYS = [60, 100, 120]      # 캘리브레이션 후 (낙관 140→120 · 아래 §대공간 검산 참조)
RENT_REV_PER_DAY = 1_757_000   # 대관 1일당 매출 = 2.67억 ÷ 152일 (02-대관BM 실측 파라미터)

def b2b_hall_days(i):
    """대공간을 쓰는 B2B 일수 — T1 전량 + T3 세션. T2는 소공간이라 제외."""
    return T1_N[i] + T3_N[i]*T3_SESSION[i]

def hall_used(i): return RENT_DAYS[i] + b2b_hall_days(i)

