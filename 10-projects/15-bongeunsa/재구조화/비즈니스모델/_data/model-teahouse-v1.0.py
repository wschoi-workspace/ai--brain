    print(f"{'  ③ 티 클럽 멤버십':<30}" + "".join(f"{eok(rev_club(i)):>15.2f}억" for i in range(3)))
    print(f"{'  매출 합계':<30}" + "".join(f"{eok(rev_all(i,plan)):>15.2f}억" for i in range(3)))
