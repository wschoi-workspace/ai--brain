# ══════════════════════════════════════════════════════════════════
# 좌석 2안 — 이 검토가 답해야 할 질문
# ══════════════════════════════════════════════════════════════════
# 소형안: RL-03 FINAL 축5 (35석 · 131㎡ = 3.74㎡/석 · 주방 최소)
# 대형안: 마스터 v0.2 (80석 · 400㎡ = 5.00㎡/석 · RL-03 FINAL의 다이닝 홀 원단위와 동일)
PLANS = {
    "소형안 (RL-03 FINAL 축5)": dict(seats=[28, 35, 42],  area=[112, 131, 150]),
    "대형안 (마스터 v0.2)":      dict(seats=[60, 80, 80],  area=[300, 400, 400]),
}
# ※ 위 area는 '오픈형 다실'의 면적이다. RL-03 FINAL 축5는 "35석·상시 개방·131㎡"로
#   오픈형만 계산했고 오마카세는 포함하지 않았다.
#   티 오마카세는 예약제 소규모라 별도 다실이 필요하므로(E-0601) 면적을 따로 더한다.
#   같은 좌석을 오픈형과 오마카세로 두 번 세지 않기 위한 처리다.
SQM_OMA_SEAT = 4.5                    # 오마카세 좌석 원단위 (다인 동선 포함 · 오픈형보다 여유)
def area_oma(i): return SEAT_OMA[i] * SQM_OMA_SEAT
def area_total(i, plan): return plan["area"][i] + area_oma(i)

# ── ① 오픈형 (E-0600) — 예약 없이 들어와 차와 한과 ──────────────
PP_OPEN  = [20_000, 26_000, 32_000]   # 객단가 — 축5 26,000원 기준
TURN     = [1.0, 1.5, 1.8]            # 회전율 — 🔴 E-0535가 지목한 미검증 가정
DAYS     = [300, 330, 350]

def rev_open(i, plan):
    return PP_OPEN[i] * plan["seats"][i] * TURN[i] * DAYS[i]

# ── ② 티 오마카세 (E-0601) — 다인이 좌석 앞에서 차를 순서대로 ──
# 국내 티 오마카세 실측 없음. 차 명상 3~7만(E-1042)과 발우공양 코스 3.6~7만(E-0424) 상단에서 설정.
PP_OMA   = [50_000, 80_000, 120_000]
SEAT_OMA = [6, 8, 10]
# 🔴 다인(茶人) 공급이 상한이다 — RL-05 검토가 확인한 진행 인력 병목과 같은 제약
SESS_OMA = [200, 400, 550]            # 연 회차 (다인 1명 1일 2회 × 영업일이 물리적 상한)
OCC_OMA  = [0.50, 0.65, 0.75]
def rev_oma(i): return PP_OMA[i] * SEAT_OMA[i] * SESS_OMA[i] * OCC_OMA[i]

# ── ③ 티 클럽 멤버십 (E-0602) — 연회비 + 시즌 차 정기 수령 ─────
# 🔴 RL-10 멤버십과 같은 지갑 (아래 중복 경고)
FEE_CLUB = [500_000, 800_000, 1_200_000]
N_CLUB   = [20, 50, 100]
def rev_club(i): return FEE_CLUB[i] * N_CLUB[i]

def rev_all(i, plan): return rev_open(i, plan) + rev_oma(i) + rev_club(i)

# ══════════════════════════════════════════════════════════════════
# 원가
# ══════════════════════════════════════════════════════════════════
# 차·한과 원가율 — 완제품 반입 시 자체 조리보다 높다(가공 마진을 남에게 준다)
COGS_SELF = [0.25, 0.22, 0.18]        # 자체 준비 가능 시
COGS_BUY  = [0.34, 0.31, 0.27]        # 완제품 반입 시 (+9%p)
WAGE = 3.5e7
CAPEX_SQM = 2_500_000                 # ㎡당 다실 조성비 (주방 설비 제외)
DEP_YEARS = 10
MKT = [0.06, 0.05, 0.04]

def staff_of(plan, i):
    """다인 + 서빙 — 좌석 12석당 1명 + 다인 1명"""
    return round(plan["seats"][i]/12 + 1, 1)

def op(i, plan, buy=False):
    rev = rev_all(i, plan)
    cogs = rev * (COGS_BUY[i] if buy else COGS_SELF[i])
    labor = staff_of(plan, i) * WAGE
    capex = area_total(i, plan) * CAPEX_SQM
    return rev - cogs - labor - rev*MKT[i] - capex/DEP_YEARS

