# -*- coding: utf-8 -*-
"""봉은문화센터 수익성 모델 v0.1 — 17개 수익 라인 × 3구간
원칙: 모든 드라이버에 근거등급(A=원자료/공식, B=벤치마크 유추, C=순수 가정)을 붙인다.
      C등급 드라이버로 만든 금액은 '추정'이 아니라 '가정'으로 표기한다.
"""
CASE = ["보수", "기준", "낙관"]

# ── 분모: 문화센터 연간 방문객(CV) ─────────────────────────────
# 비신도 내국인은 근거 0건이라 0으로 둔 하방 모델이다.
FOREIGN = [100_000, 300_000, 609_390]   # E-1052 하한 / 중간 / E-0310 실측 상한 (A~B)
DEVOTEE = [200_000, 200_000, 200_000]   # E-0513 연 신도 20만 (B)
DEV_IN  = [0.50, 0.75, 1.00]            # 신도의 문화센터 진입률 (C)
FOR_IN  = [0.60, 0.75, 0.90]            # 외국인의 문화센터 진입률 (C)
CV = [int(FOREIGN[i]*FOR_IN[i] + DEVOTEE[i]*DEV_IN[i]) for i in range(3)]

# ── 라인별 드라이버 ────────────────────────────────────────────
# (코드, 라인명, 게이트, 등급, 계산함수, 드라이버설명)
# 게이트: T1=지금 가능 / COOK=조리 해소 필요 / T2=유권해석 필요
def m(v): return v/1e8  # 원 → 억

L = []
def add(code, name, gate, grade, amounts, driver):
    L.append(dict(code=code, name=name, gate=gate, grade=grade, amt=amounts, driver=driver))

# RL-01 전시 입장 — 유료전환 × 티켓
p01_conv = [0.12, 0.18, 0.25]; p01_price = [10_000, 13_000, 15_000]
add("RL-01","전시 입장","T1","C",
    [CV[i]*p01_conv[i]*p01_price[i] for i in range(3)],
    "CV × 유료전환 12/18/25%(C) × 티켓 1.0/1.3/1.5만원(C) ※92억모델은 1.5만×400명×350일")

# RL-02 F&B 전통다원 — 400㎡/5㎡ = 80석
p02_seat=[60,80,80]; p02_price=[15_000,20_000,25_000]; p02_turn=[1.0,1.5,2.0]; p02_day=[300,330,350]
add("RL-02","F&B · 전통다원","COOK","B",
    [p02_seat[i]*p02_price[i]*p02_turn[i]*p02_day[i] for i in range(3)],
    "좌석 60/80/80(C·F&B 1,000㎡ 중 400㎡) × 객단가 1.5/2.0/2.5만(A·E-0149) × 회전 1.0/1.5/2.0(C) × 영업일 300/330/350(C)")

# RL-03 F&B 사찰음식 다이닝 — 600㎡ → 80석
p03_seat=[60,80,80]; p03_price=[50_000,70_000,90_000]; p03_turn=[1.0,1.5,2.0]; p03_day=[280,300,320]
add("RL-03","F&B · 사찰음식 다이닝","COOK","B",
    [p03_seat[i]*p03_price[i]*p03_turn[i]*p03_day[i] for i in range(3)],
    "좌석 60/80/80(C) × 코스 5/7/9만(A·E-0182 5~10만) × 회전 1.0/1.5/2.0(C) × 영업일 280/300/320(C) ※발우공양 실적 일120명(E-0424)")

# RL-04 리테일
p04_conv=[0.15,0.215,0.30]; p04_price=[6_400,12_000,20_000]
add("RL-04","리테일 · 상품판매","T1","B",
    [CV[i]*p04_conv[i]*p04_price[i] for i in range(3)],
    "CV × 구매전환 15/21.5/30%(A·E-1006 외국인 21.5%) × 객단가 6,400/12,000/20,000원(B·뮷즈 413억÷650만명 역산)")

# RL-05 교육·체험 클래스
p05_price=[50_000,70_000,100_000]; p05_cap=[16,16,20]; p05_util=[0.50,0.65,0.80]; p05_ses=[300,600,900]
add("RL-05","교육 · 체험 클래스","T2","B",
    [p05_price[i]*p05_cap[i]*p05_util[i]*p05_ses[i] for i in range(3)],
    "회차단가 5/7/10만(B·E-1042 권고 5~10만) × 정원 16/16/20(B·E-1007) × 가동 50/65/80%(C) × 연회차 300/600/900(C)")

# RL-06 명상 B2C (회차권) — 도보권 11.2만
p06_pen=[0.01,0.03,0.05]; p06_freq=[10,20,30]; p06_price=[3_000,5_000,8_000]
add("RL-06","명상 프로그램 (B2C)","T2","B",
    [112_349*p06_pen[i]*p06_freq[i]*p06_price[i] for i in range(3)],
    "도보권 112,349명(A·E-1021) × 침투 1/3/5%(C) × 연이용 10/20/30회(C) × 회차단가 3,000/5,000/8,000원(A·E-1016 선릉 3,000원)")

# RL-07 기업 B2B
p07_price=[1_500_000,2_500_000,4_000_000]; p07_n=[30,80,150]
add("RL-07","기업 B2B 프로그램","T2","B",
    [p07_price[i]*p07_n[i] for i in range(3)],
    "회당 150/250/400만(B·E-1040 권고 150~300만 vs E-0154 100~500만 충돌) × 연 30/80/150건(C)")

# RL-08 대관 — 대관홀 1,500㎡
p08_rate=[1_150,2_000,3_202]; p08_day=[60,100,150]
add("RL-08","대관","T2","A",
    [1_500*p08_rate[i]*p08_day[i] for i in range(3)],
    "대관홀 1,500㎡(A·E-0532) × 단가 1,150/2,000/3,202원/㎡·일(A·E-1079) × 가동 60/100/150일(C)")

# RL-09 숙박·체류
p09_room=[10,20,30]; p09_rate=[100_000,120_000,150_000]; p09_occ=[0.30,0.45,0.60]
add("RL-09","숙박 · 체류","T2","B",
    [p09_room[i]*p09_rate[i]*p09_occ[i]*365 for i in range(3)],
    "객실 10/20/30(C) × 박단가 10/12/15만(A·E-0428 9~12만) × 가동 30/45/60%(C) × 365일")

# RL-10 멤버십 — 법인 + 임원기수 + 개인
p10_corp_fee=[5_000_000,7_500_000,10_000_000]; p10_corp_n=[10,30,60]
p10_exec_fee=[5_000_000,6_500_000,8_000_000]; p10_exec_n=[20,40,60]
p10_ind_fee=[300_000,400_000,500_000];        p10_ind_n=[200,1_000,3_000]
add("RL-10","멤버십 · 구독","T2","B",
    [p10_corp_fee[i]*p10_corp_n[i] + p10_exec_fee[i]*p10_exec_n[i] + p10_ind_fee[i]*p10_ind_n[i] for i in range(3)],
    "법인 500/750/1,000만×10/30/60사(A단가 E-1041) + 임원기수 500/650/800만×20/40/60명(A단가 E-1047) + 개인 30/40/50만×200/1,000/3,000명(C — 국내 리텐션 사례 0건)")

# RL-11 장묘 — 봉안 한도 5,000기
p11_n=[200,400,600]; p11_price=[3_000_000,5_000_000,10_000_000]
add("RL-11","장묘 · 라이프엔딩","T2","B",
    [p11_n[i]*p11_price[i] for i in range(3)],
    "연 분양 200/400/600기(C) × 분양가 300/500/1,000만(B·E-0445 국공립 75~150만·사설 1,000만~1억) ※종교단체 한도 5,000기 → 누적 상한 존재")

# RL-12 온라인 판매 — 오프라인 리테일 대비 비율
p12_ratio=[0.20,0.35,0.50]
add("RL-12","온라인 판매","T2","C",
    [ (CV[i]*p04_conv[i]*p04_price[i]) * p12_ratio[i] for i in range(3)],
    "RL-04 × 20/35/50%(C·뮷즈 오프라인 234억/전체 413억 = 온라인 43% 참조) ※채널 자체 미구축(E-1004)")

# RL-13 시즌·야간 이벤트
p13_visitor=[30_000,80_000,150_000]; p13_arpu=[5_000,8_000,12_000]
add("RL-13","시즌 · 야간 이벤트","T2","C",
    [p13_visitor[i]*p13_arpu[i] for i in range(3)],
    "시즌 관람 3/8/15만명(C) × 객단가 5,000/8,000/12,000원(C) ※국내 단가 근거 0")

# RL-14 [C] 도매·공급
p14_temple=[20,60,120]; p14_order=[5_000_000,10_000_000,20_000_000]
add("RL-14","[C] 도매 · 공급","T2","C",
    [p14_temple[i]*p14_order[i] for i in range(3)],
    "거래 사찰 20/60/120곳(C) × 연 발주 500/1,000/2,000만(C) ※도매단가 근거 0 · G10 수요 미연결률 85%")

# RL-15 [C] IP·라이선스
p15_gmv=[1_000_000_000,3_000_000_000,8_000_000_000]; p15_rate=[0.05,0.07,0.10]
add("RL-15","[C] IP · 라이선스","T2","C",
    [p15_gmv[i]*p15_rate[i] for i in range(3)],
    "파트너 매출 10/30/80억(C) × 로열티 5/7/10%(C) ※성물 등급심의(E-0704) 선행")

# RL-16 [C] 용역·턴키·교육
p16_fee=[30_000_000,50_000_000,100_000_000]; p16_n=[3,8,15]
add("RL-16","[C] 용역 · 턴키 · 교육","T2","C",
    [p16_fee[i]*p16_n[i] for i in range(3)],
    "건당 3,000/5,000만/1억(C) × 연 3/8/15건(C) ※근거 0")

# RL-17 자체 상품개발 — RL-04로 귀속
add("RL-17","[C] 상품개발 · 직영","T1","—",[0,0,0],"원가 라인 — 매출은 RL-04에 귀속 (이중계상 방지)")

# ── 게이트 시나리오 ────────────────────────────────────────────
GATES = {
 "좁게(Tier1만·조리 불가)": lambda x: x["gate"]=="T1",
 "중간(Tier2 열림·조리 불가)": lambda x: x["gate"] in ("T1","T2"),
 "넓게(Tier2+조리 해소)":     lambda x: True,
}

if __name__ == "__main__":
    print("="*112)
    print("분모 — 문화센터 연간 방문객(CV)   ※비신도 내국인 0 가정한 하방 모델")
    print("="*112)
    for i,c in enumerate(CASE):
        print(f"  {c:<4} 외국인 {FOREIGN[i]:>7,}×{FOR_IN[i]:.0%} + 신도 {DEVOTEE[i]:>7,}×{DEV_IN[i]:.0%}  =  CV {CV[i]:>9,}명")
    print()
    print("="*112)
    print("수익 라인별 매출 (억원)")
    print("="*112)
    print(f"{'코드':<7}{'라인명':<22}{'게이트':<7}{'등급':<5}{'보수':>9}{'기준':>9}{'낙관':>9}")
    print("-"*112)
    for x in L:
        print(f"{x['code']:<7}{x['name']:<22}{x['gate']:<7}{x['grade']:<5}"
              f"{m(x['amt'][0]):>9.1f}{m(x['amt'][1]):>9.1f}{m(x['amt'][2]):>9.1f}")
    print("-"*112)
    tot=[sum(x['amt'][i] for x in L) for i in range(3)]
    print(f"{'':<41}{'합계':<0}{m(tot[0]):>9.1f}{m(tot[1]):>9.1f}{m(tot[2]):>9.1f}")
    print()
    print("="*112)
    print("게이트 × 방문객 교차 — 총매출(억원) / 기준선 30억 대비")
    print("="*112)
    print(f"{'유권해석 시나리오':<28}{'보수':>16}{'기준':>16}{'낙관':>16}")
    print("-"*112)
    for gname, f in GATES.items():
        vals=[sum(x['amt'][i] for x in L if f(x)) for i in range(3)]
        cells=[]
        for i in range(3):
            v=m(vals[i]); r=v/30
            mark = "✓" if v>=30 else "✗"
            cells.append(f"{v:>8.1f}억 {r:>4.2f}x{mark}")
        print(f"{gname:<28}" + "".join(f"{c:>16}" for c in cells))
    print()
    print("="*112)
    print("드라이버 원장")
    print("="*112)
    for x in L:
        print(f"[{x['code']}] {x['name']}  (등급 {x['grade']} · 게이트 {x['gate']})")
        print(f"    {x['driver']}")
