def interest_schedule(amount, rate, grace, repay, years=5):
    """거치기간 이자만, 상환기간 원금균등+이자. 5년치 반환(억원)"""
    out=[]
    bal = amount
    for y in range(1, years+1):
        i = bal*rate
        p = 0.0
        if grace is not None and y > grace:
            p = amount/repay
            bal = max(0.0, bal-p)
        out.append((i, p))
    return out

def plan_cost(plan, years=5):
    """5개년 이자비용·원금상환 합계"""
    ints=[0.0]*years; prins=[0.0]*years
    for src, amt in plan.items():
        s = SOURCES[src]
        if s['rate'] == 0: continue
        sch = interest_schedule(amt, s['rate'], s['grace'], s['repay'], years)
        for y,(i,p) in enumerate(sch):
            ints[y]+=i; prins[y]+=p
    return ints, prins

def own_capital(plan):
    return plan.get("종단 출연·자기자본", 0.0)

