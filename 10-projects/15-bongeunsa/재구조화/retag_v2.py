P_MAP = {"S8-P1": "S8-A", "S8-P2": "S8-B", "S8-P3": "S8-A", "S8-P4": "S8-C"}


def add_slot(el, slot, angle):
    """slot·rendering 을 함께 추가. 이미 있으면 아무것도 하지 않는다."""
    if slot in el.get("slots", []):
        return False
    el.setdefault("slots", []).append(slot)
    el.setdefault("renderings", []).append({"slot": slot, "angle": angle})
    return True


def remap_p(el):
    """S8-P1~P4 를 A·B·C 로 치환. slots·renderings 를 함께 바꾸고 중복은 병합한다."""
    slots = el.get("slots", [])
    if not any(s in P_MAP for s in slots):
        return False

    new_slots = []
    for s in slots:
        t = P_MAP.get(s, s)
        if t not in new_slots:
            new_slots.append(t)

    # renderings: slot 이름 치환 후, 같은 슬롯으로 합쳐지면 angle 을 이어 붙인다
    merged = {}
    order = []
    for r in el.get("renderings", []):
        t = P_MAP.get(r.get("slot"), r.get("slot"))
        angle = (r.get("angle") or "").strip()
        if t in merged:
            if angle and angle not in merged[t]:
                merged[t] = merged[t] + " · " + angle
        else:
            merged[t] = angle
            order.append(t)
    el["slots"] = new_slots
    el["renderings"] = [{"slot": t, "angle": merged[t]} for t in order if t in new_slots]
    return True


def main():
    n = {"S4-O5": 0, "S2-c3": 0, "S5-BM5": 0, "P→ABC": 0}
    seen = set()

    for path in sorted(glob.glob("shards/*.json")):
        data = json.load(open(path, encoding="utf-8"))
        changed = False
        for el in data:
            eid = el.get("id")
            seen.add(eid)
            if eid in S4_O5 and add_slot(el, "S4-O5", S4_O5[eid]):
                n["S4-O5"] += 1; changed = True
            if eid in S2_C3 and add_slot(el, "S2-c3", S2_C3[eid]):
                n["S2-c3"] += 1; changed = True
            if eid in S5_BM5 and add_slot(el, "S5-BM5", S5_BM5[eid]):
                n["S5-BM5"] += 1; changed = True
            if remap_p(el):
                n["P→ABC"] += 1; changed = True
        if changed:
            json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
            print(f"  patched {path}")

    missing = sorted((set(S4_O5) | set(S2_C3) | set(S5_BM5)) - seen)
    if missing:
        print(f"⚠️ shard 에 없는 ID: {', '.join(missing)}")

    print(f"S4-O5 +{n['S4-O5']} / S2-c3 +{n['S2-c3']} / S5-BM5 +{n['S5-BM5']} / P→ABC {n['P→ABC']}건")


if __name__ == "__main__":
    main()
